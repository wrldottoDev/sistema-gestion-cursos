// Concatenate src/*.js (sorted) into code.js — no dependencies.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = dirname(fileURLToPath(import.meta.url));
const files = readdirSync(join(root, 'src')).filter(f => f.endsWith('.js')).sort();
const out = '// GENERATED by build.mjs — edit src/*.js\n' + files.map(f => `// ---- ${f}\n` + readFileSync(join(root, 'src', f), 'utf8')).join('\n');
writeFileSync(join(root, 'code.js'), out);
console.log('code.js', out.length, 'bytes from', files.join(', '));
